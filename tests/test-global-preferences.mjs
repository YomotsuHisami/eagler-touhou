import assert from "node:assert/strict";
import { loadGlobalGamePreferences, persistGlobalGamePreferences, normalizeStoredGamePreferences, effectiveThpracEnabled } from "../.cache/build/browser/assets/launcher/game-preferences.mjs";
const items = new Map();
const storage = { getItem: key => items.get(key) ?? null, setItem: (key, value) => items.set(key, value) };
const legacy = normalizeStoredGamePreferences({ options: { thpracEnabled: true, frameLimit60Enabled: true, touchEnabled: true }, music: "midi", musicPreferenceExplicit: true }, { thpracAvailable: true, webAudioAvailable: true });
const shared = loadGlobalGamePreferences(storage, legacy, "zh");
assert.equal(shared.options.frameLimit60Enabled, true);
assert.equal(shared.options.touchEnabled, true);
assert.equal(effectiveThpracEnabled(shared.options.thpracEnabled, false, false), false);
assert.equal(effectiveThpracEnabled(shared.options.thpracEnabled, true, true), false);
assert.equal(effectiveThpracEnabled(true, undefined, false), false, "missing capability fails closed");
assert.equal(shared.options.thpracEnabled, true, "unsupported games must not erase requested preference");
persistGlobalGamePreferences(storage, shared);
const other = loadGlobalGamePreferences(storage, normalizeStoredGamePreferences(null, { thpracAvailable: false, webAudioAvailable: true }), "en");
assert.equal(other.options.frameLimit60Enabled, true);
assert.equal(other.options.touchEnabled, true);
assert.equal(other.musicPreference, "midi");
assert.equal(effectiveThpracEnabled(other.options.thpracEnabled, true, false), true, "supported game restores effective feature");
console.log("Global preferences and thprac capability fallback: PASS");
